/* 收集全部结局，按剧本内顺序（含 endings 规则表里的结局） */
var ALL_ENDINGS = (function () {
  var out = [];
  var seen = {};
  function push(e) {
    if (e && e.id && !seen[e.id]) { seen[e.id] = true; out.push(e); }
  }
  for (var k in STORY) {
    if (!Object.prototype.hasOwnProperty.call(STORY, k)) continue;
    var sc = STORY[k];
    push(sc.ending);
    if (sc.endings) {
      for (var i = 0; i < sc.endings.length; i++) push(sc.endings[i].ending);
    }
  }
  return out;
})();

